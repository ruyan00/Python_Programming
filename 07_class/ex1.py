# 1. 클래스 기초

# ===========================================================
#  0. 데이터와 기능을 따로 관리할 때의 문제점
#  1) 데이터 구조가 바뀌면 데이터를 사용하는 모든 함수를 찾아 수정해줘야 함 -> ( 유지보수 )의 어려움
#  2) 프로그램 어디서나 데이터에 접근할 수 있어 의도치 않은 오류가 날 수 있음 -> ( 데이터 무결성 )이 깨짐
#  3) 데이터와 기능이 분리되어 있어 재사용성이 떨어짐 -> ( 코드 재사용성 ), ( 확장성 )이 떨어짐
# ===========================================================

# ===========================================================
#  1. ( 객체지향 ) 프로그래밍 (OOP, Object Oriented Programming)
#  : 관련된 ( 데이터 )와 ( 기능 )을 ( 객체 )라는 독립된 단위로 묶어
#    이들의 상호작용으로 프로그램을 구성하는 프로그래밍 패러다임
#
#  [구조체 vs 클래스]
#  - 구조체: 데이터만 묶을 수 있고, 함수는 따로 만들어야 함
#  - 클래스: 데이터(속성) + 함수(메소드)를 한 곳에 묶음
# ===========================================================

# ===========================================================
#  2. 용어 정리
#  1) ( 클래스, class )
#  - 객체를 만들기 위한 ( 설계도 ) (예: 붕어빵 틀, 자동차 설계도)
#  - 클래스 자체는 데이터를 담는 실체가 아니라 틀임
#
#  2) ( 객체, object )
#  - 클래스(설계도)로 만들어진 ( 실체 ) (예: 붕어빵, 자동차)
#  - 하나의 클래스로 객체를 여러 개 만들 수 있음 (객체는 서로 독립적임)
#
#  3) ( 속성, attribute ): 객체가 가진 ( 데이터 ) (예: 이름, 나이, 키)
#
#  4) ( 메소드, method ): 객체가 할 수 있는 ( 기능 ) (예: 먹기, 공부하기)
# ===========================================================


