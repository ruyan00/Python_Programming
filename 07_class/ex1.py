# ===========================================================
#  6. self와 인스턴스 변수
#  - self: 메소드를 호출한 ( 객체 자기 자신 )을 가리키는 변수 (관례적 이름)
#  - 인스턴스 변수: 각 객체가 개별적으로 가지는 독립적인 변수
#  - 객체명.변수명(클래스 밖), self.변수명으로 접근(클래스 내)
#  -> 인스턴스 변수는 반드시 ( 객체 )를 생성한 후 사용 가능
# ===========================================================


class Dog:
    # 생성자의 역할 : 객체를 초기화
    # 인스턴스 변수 초기화, 객체 생성 시 실행해야 되는 로직 구현 (파일 로드, DB Conn 설정)
    def __init__(self, name, age):
        self.name = name  # 인스턴스변수 = 매개변수(지역변수)
        if age < 0:
            self.age = 0
        else:
            self.age = age

    def bark(self):
        print(f"{self.name} 멍멍")

    def introduce(self):
        print(f"저는 {self.name} {self.age}살 입니다.")


d1 = Dog("고별", 10)
print(d1.name, d1.age)

d2 = Dog("뽀삐", 5)
print(d2.name, d2.age)

d1.name = "고별2"
print(d1.name, d2.name)

